"""Согласование числа с существительным: 1 автотест, 2–4 автотеста, 5–20 автотестов, 11–14 — как 5–20."""

from __future__ import annotations

# Формы для числительного в именительном и винительном падеже: (1, 2–4, 5–20).
FORMS: dict[str, tuple[str, str, str]] = {
    "автотест": ("автотест", "автотеста", "автотестов"),
    "демо-кейс": ("демо-кейс", "демо-кейса", "демо-кейсов"),
    "правил": ("правило", "правила", "правил"),
}

# После этих предлогов существительное стоит в родительном падеже («из 1384 автотестов»), и форма по числу
# не выбирается.
GENITIVE_PREPOSITIONS = {"из", "для", "от", "до", "около", "без", "у", "свыше", "более", "менее"}


def plural(n: int, one: str, few: str, many: str) -> str:
    """Форма существительного для числа n."""
    n = abs(n)
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def count_phrase(n: int, stem: str) -> str:
    """«1384 автотеста»: число и согласованная форма слова из FORMS."""
    return f"{n} {plural(n, *FORMS[stem])}"
